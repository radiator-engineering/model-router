#!/usr/bin/env node
// Claude's hook loader accepts code modules, not JSON imports.
// Generates the full document, never the legacy projection.
import {readFile, writeFile} from 'node:fs/promises';
import {pathToFileURL} from 'node:url';
import {parseCatalogDocument, migrateCatalogV1} from '../hooks/model-catalog.ts';

/** JSON.parse preserves own __proto__ keys; a JS object literal would not. */
export function renderCatalog(catalog) {
  return '// Generated by node scripts/build-catalog.mjs. Edit models.json, not this file.\n' +
    'export default JSON.parse(' + JSON.stringify(JSON.stringify(catalog, null, 2)) + ')\n';
}

async function main() {
  const source = new URL('../catalog/models.json', import.meta.url);
  const destination = new URL('../catalog/model-data.ts', import.meta.url);
  if (process.argv.slice(2).some(arg => arg !== '--check')) throw new Error('Usage: node scripts/build-catalog.mjs [--check]');
  const check = process.argv.includes('--check');
  let catalog = parseCatalogDocument(JSON.parse(await readFile(source, 'utf8')));
  if (catalog.schemaVersion === 1) {
    if (check) throw new Error('catalog/models.json is schema v1. Run node scripts/build-catalog.mjs to migrate it.');
    catalog = migrateCatalogV1(catalog);
    // Validate/migrate completely before either output is written.
    await writeFile(source, JSON.stringify(catalog, null, 2) + '\n');
    console.log('Migrated catalog/models.json to schema v2');
  }
  const output = renderCatalog(catalog);
  if (check) {
    if (await readFile(destination, 'utf8') !== output) throw new Error('Catalog module is stale. Run node scripts/build-catalog.mjs');
    console.log('Generated catalog matches models.json.');
  } else {
    await writeFile(destination, output);
    console.log('Generated catalog/model-data.ts');
  }
}
if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) await main();
