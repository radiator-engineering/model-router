#!/usr/bin/env node
// Claude's hook loader accepts code modules, not JSON imports.
import {readFile, writeFile} from 'node:fs/promises';
import {parseCatalog} from '../hooks/model-catalog.ts';
const source = new URL('../catalog/models.json', import.meta.url);
const destination = new URL('../catalog/model-data.ts', import.meta.url);
const catalog = parseCatalog(JSON.parse(await readFile(source,'utf8')));
const output = '// Generated by node scripts/build-catalog.mjs. Edit models.json, not this file.\nexport default '+JSON.stringify(catalog,null,2)+'\n';
if (process.argv.includes('--check')) {
  if (await readFile(destination,'utf8') !== output) throw new Error('Catalog module is stale. Run node scripts/build-catalog.mjs');
  console.log('Generated catalog matches models.json.');
} else {
  await writeFile(destination,output); console.log('Generated catalog/model-data.ts');
}
